/**
 * Tra cứu chính xác tiêu chuẩn lương theo Công việc và Chức vụ
 */
export function findTieuChuanLuong(
  congViec?: string,
  chucVu?: string
): TieuChuanLuongItem | undefined {
  if (!chucVu) return undefined;
  const cleanPos = chucVu.trim().toLowerCase();
  const cleanJob = congViec ? congViec.trim().toLowerCase() : '';

  // 1. Khớp chính xác cả công việc và chức vụ
  if (cleanJob) {
    const exact = DEFAULT_TIEU_CHUAN_LUONG.find(
      (item) =>
        (item.congViec.toLowerCase() === cleanJob || cleanJob.includes(item.congViec.toLowerCase())) &&
        item.chucVu.toLowerCase() === cleanPos
    );
    if (exact) return exact;
  }

  // 2. Khớp chính xác chức vụ (không phân biệt chữ hoa thường)
  const exactPos = DEFAULT_TIEU_CHUAN_LUONG.find(
    (item) => item.chucVu.toLowerCase() === cleanPos
  );
  if (exactPos) return exactPos;

  // 3. Khớp tương đối chức vụ (chứa tên chức vụ)
  return DEFAULT_TIEU_CHUAN_LUONG.find(
    (item) =>
      cleanPos.includes(item.chucVu.toLowerCase()) ||
      item.chucVu.toLowerCase().includes(cleanPos)
  );
}

/**
 * Kiểm tra xem vị trí công việc có thuộc bảng tiêu chuẩn hay không
 */
export function isStandardPosition(congViec?: string, chucVu?: string): boolean {
  return !!findTieuChuanLuong(congViec, chucVu);
}
